// Generate apply-descriptions.sql — emits sp_addextendedproperty /
// sp_updateextendedproperty calls so descriptions in descriptions.json
// land on the actual SQL Server objects as MS_Description.
// Re-run with: node src/generate-ms-description-sql.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DESCRIPTIONS_PATH = path.join(ROOT, 'descriptions.json');
const SQL_OUT = path.join(ROOT, 'apply-descriptions.sql');

function loadDescriptions() {
  const raw = JSON.parse(fs.readFileSync(DESCRIPTIONS_PATH, 'utf8'));
  const out = [];
  for (const [k, v] of Object.entries(raw)) {
    if (k.startsWith('_')) continue;
    if (typeof v !== 'string' || !v.trim()) continue;
    const parts = k.split('.');
    if (parts.length === 3) {
      out.push({ kind: 'object', db: parts[0], schema: parts[1], name: parts[2], desc: v.trim() });
    } else if (parts.length === 4) {
      out.push({ kind: 'column', db: parts[0], schema: parts[1], name: parts[2], column: parts[3], desc: v.trim() });
    }
    // Other shapes are reported by validate-descriptions.js, not here.
  }
  return out;
}

function escapeSql(s) {
  return s.replace(/'/g, "''");
}

function emitForObject(e) {
  // Quote SQL Server identifiers safely; descriptions.json keys are
  // controlled and known-good, but defense in depth is cheap.
  const safe = (id) => `[${id.replace(/]/g, ']]')}]`;
  const dbQ = safe(e.db);
  const schemaLit = `'${escapeSql(e.schema)}'`;
  const nameLit = `'${escapeSql(e.name)}'`;
  const descLit = `N'${escapeSql(e.desc)}'`;

  if (e.kind === 'column') {
    const colLit = `'${escapeSql(e.column)}'`;
    return `USE ${dbQ};
IF EXISTS (
    SELECT 1 FROM sys.fn_listextendedproperty(
        N'MS_Description', N'SCHEMA', ${schemaLit}, N'TABLE', ${nameLit}, N'COLUMN', ${colLit})
)
    EXEC sp_updateextendedproperty
        @name = N'MS_Description',
        @value = ${descLit},
        @level0type = N'SCHEMA', @level0name = ${schemaLit},
        @level1type = N'TABLE',  @level1name = ${nameLit},
        @level2type = N'COLUMN', @level2name = ${colLit};
ELSE
    EXEC sp_addextendedproperty
        @name = N'MS_Description',
        @value = ${descLit},
        @level0type = N'SCHEMA', @level0name = ${schemaLit},
        @level1type = N'TABLE',  @level1name = ${nameLit},
        @level2type = N'COLUMN', @level2name = ${colLit};
GO
`;
  }

  return `USE ${dbQ};
IF EXISTS (
    SELECT 1 FROM sys.fn_listextendedproperty(
        N'MS_Description', N'SCHEMA', ${schemaLit}, N'TABLE', ${nameLit}, NULL, NULL)
)
    EXEC sp_updateextendedproperty
        @name = N'MS_Description',
        @value = ${descLit},
        @level0type = N'SCHEMA', @level0name = ${schemaLit},
        @level1type = N'TABLE',  @level1name = ${nameLit};
ELSE
    EXEC sp_addextendedproperty
        @name = N'MS_Description',
        @value = ${descLit},
        @level0type = N'SCHEMA', @level0name = ${schemaLit},
        @level1type = N'TABLE',  @level1name = ${nameLit};
GO
`;
}

(() => {
  const entries = loadDescriptions();

  const out = [];
  const objectCount = entries.filter((e) => e.kind === 'object').length;
  const columnCount = entries.filter((e) => e.kind === 'column').length;
  out.push('-- Generated by src/generate-ms-description-sql.js');
  out.push(`-- Source: descriptions.json (${entries.length} entries: ${objectCount} object, ${columnCount} column)`);
  out.push('-- Applies MS_Description extended properties to tables, views, and columns.');
  out.push('-- Idempotent: updates if present, inserts if missing.');
  out.push('-- Notes:');
  out.push("--   * @level1type = 'TABLE' is correct for both tables AND views in SQL Server.");
  out.push("--   * @level2type = 'COLUMN' is used for column-level descriptions.");
  out.push('--   * Run with sqlcmd: sqlcmd -S <server> -U <user> -P <pwd> -i apply-descriptions.sql');
  out.push("--   * Wrap in BEGIN TRAN / COMMIT manually if you want all-or-nothing semantics.");
  out.push('');
  out.push('SET NOCOUNT ON;');
  out.push('GO');
  out.push('');

  for (const e of entries) {
    out.push(emitForObject(e));
  }

  out.push('-- Verify object-level descriptions with:');
  out.push('-- USE EDS;');
  out.push("-- SELECT s.name AS [schema], o.name AS [object], CAST(ep.value AS NVARCHAR(MAX)) AS description");
  out.push('-- FROM sys.extended_properties ep');
  out.push('-- JOIN sys.objects o ON ep.major_id = o.object_id AND ep.minor_id = 0');
  out.push('-- JOIN sys.schemas s ON o.schema_id = s.schema_id');
  out.push("-- WHERE ep.name = N'MS_Description' AND ep.class = 1");
  out.push('-- ORDER BY s.name, o.name;');
  out.push('--');
  out.push('-- Verify column-level descriptions with:');
  out.push("-- SELECT s.name AS [schema], o.name AS [table], c.name AS [column], CAST(ep.value AS NVARCHAR(MAX)) AS description");
  out.push('-- FROM sys.extended_properties ep');
  out.push('-- JOIN sys.objects o  ON ep.major_id = o.object_id');
  out.push('-- JOIN sys.columns c  ON c.object_id = o.object_id AND c.column_id = ep.minor_id');
  out.push('-- JOIN sys.schemas s  ON o.schema_id = s.schema_id');
  out.push("-- WHERE ep.name = N'MS_Description' AND ep.class = 1 AND ep.minor_id > 0");
  out.push('-- ORDER BY s.name, o.name, c.column_id;');
  out.push('');

  fs.writeFileSync(SQL_OUT, out.join('\n'));
  console.log(`Wrote ${SQL_OUT} with ${entries.length} extended-property statements`);
})();
